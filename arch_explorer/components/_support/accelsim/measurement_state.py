# Concrete Accel-Sim implementation; owned by the component provider.
"""One registry-owned finite measurement plan. No device/resource operations.

v3 selects complete programs by reference, not by editing ISA or old registries.
The generated bytes are embedded in both the real host and CPU Driver harness.
"""
import hashlib,json,re
from pathlib import Path
from arch_explorer.components.accelsim.trace import exact,digest,same_json

REGISTRY='arch-explorer.measurement-registry.v3'
PLAN='arch-explorer.measurement-state-plan.v1'
MAGIC=b'AE-MEASUREMENT-STATE-V1\n'
SECTION='.ae_measurement'
EXECUTOR=Path(__file__).with_name('state_executor.hpp')
CPU=Path(__file__).with_name('state_cpu.cpp')
LIFECYCLE={'input':'upload-once-immutable','output':'reset-a5-before-each-launch',
 'synchronize':'context-before-start;stop-event-after-launch',
 'allocation':'per-case-host-reuse-all-roles','events':'one-pair-per-case-host-reuse-all-roles',
 'interval':'record-start;one-registered-launch;record-stop',
 'first_diagnostic_scope':'first-registered-execution-in-this-host-context;hardware-cold-unproven',
 'preparation_scope':'fixed-experiment-condition;steady-state-unproven'}
ROLES=('diagnostic','preparation','formal')

def stateful(bundle):return bundle.document.get('schema')==REGISTRY
def sha_plan(bundle):return digest(json.dumps(bundle.document['measurement_state'],sort_keys=True,separators=(',',':')).encode())

def validate_plan(plan,cases):
    exact(plan,{'schema','lifecycle','cases'},'measurement state plan')
    if plan['schema']!=PLAN or not same_json(plan['lifecycle'],LIFECYCLE):raise ValueError('unknown measurement lifecycle/version')
    if not isinstance(plan['cases'],list) or [r.get('case') for r in plan['cases']]!=list(cases):raise ValueError('plan case order differs from registry')
    for row in plan['cases']:
        exact(row,{'case','diagnostic','preparation','formal'},'fixed role counts')
        if any(type(row[k]) is not int for k in ROLES) or row['diagnostic']!=1 or not 0<=row['preparation']<=8 or row['formal']!=3:
            raise ValueError('fixed diagnostic/preparation/three-formal counts required')
    return plan

def slots(bundle,cid):
    row=next(r for r in bundle.document['measurement_state']['cases'] if r['case']==cid)
    return [dict(sequence=i,role=role,role_index=j,formal_index=j if role=='formal' else None)
            for i,(role,j) in enumerate((role,j) for role in ROLES for j in range(row[role]))]

def validate_budget(bundle):
    from arch_explorer.components.accelsim.microcontract import CAPS
    b=bundle.document['budget'];n=len(bundle.cases)
    added={'diagnostic_launches','preparation_launches','uninstrumented_launches','application_launches'}
    exact(b,set(CAPS)|added,'complete role budget')
    base={k:b[k] for k in CAPS}
    from arch_explorer.components.accelsim.microcontract import validate_budget as old_budget
    old_budget(base,n)
    counts={role:sum(r[role] for r in bundle.document['measurement_state']['cases']) for role in ROLES}
    expected={'diagnostic_launches':counts['diagnostic'],'preparation_launches':counts['preparation'],
              'uninstrumented_launches':sum(counts.values()),'application_launches':n+sum(counts.values())}
    if any(type(b[k]) is not int or b[k]!=v for k,v in expected.items()):raise ValueError('all-role denominator/budget differs')
    return b

def load_registry(path,data,raw):
    from arch_explorer.components.accelsim.microbundle import Bundle,json_file,load_registry as programs
    from arch_explorer.components.accelsim.microrecords import original
    exact(data,{'schema','work_item','program_registry','case_ids','measurement_state','budget',
                'physical_parameters','hardware_accuracy','gpu_observations'},'state registry')
    if data['schema']!=REGISTRY or not re.fullmatch(r'WP-SIM-[0-9]+[A-Z]?',data['work_item']):raise ValueError('state registry identity')
    source=programs(original(data['program_registry']))
    if stateful(source):raise ValueError('state plan cannot recursively select a state registry')
    ids=data['case_ids']
    if not isinstance(ids,list) or not 1<=len(ids)<=12 or len(set(ids))!=len(ids) or any(k not in source.cases for k in ids):raise ValueError('complete registered case selection required')
    if ids!=[k for k in source.cases if k in ids]:raise ValueError('program selection changes registered order')
    cases={k:source.cases[k] for k in ids}
    if {c['partition'] for c in cases.values()}!={'fit','heldout'}:raise ValueError('explicit fit and heldout required')
    validate_plan(data['measurement_state'],cases)
    if data['physical_parameters'] is not None or data['hardware_accuracy']!='not validated' or data['gpu_observations']!=0:raise ValueError('CPU registry cannot assert physical observations')
    # Derived immutable views retain the complete program document's fields.
    # The only authority remains program_registry + its ordered case_ids.
    doc=dict(source.document);doc.update(data);doc['cases']=list(cases.values())
    flow=sum(c['full_flow_instructions'] for c in cases.values());static=sum(len(source.static[c['function']]['instructions']) for c in cases.values())
    bounds={'dynamic_records':flow,'static_instructions':static,'records_bytes':64*len(ids)+288*flow,
            'static_bytes':40*static+len(ids)*(64*2048+4096),'other_capture_bytes':2**20}
    bounds['aggregate_capture_max_bytes']=sum(bounds[k] for k in ('records_bytes','static_bytes','other_capture_bytes'))
    bundle=Bundle(Path(path),doc,digest(raw),{c['function']:source.static[c['function']] for c in cases.values()},
                  {c['function']:source.texts[c['function']] for c in cases.values()},cases,bounds,source.path.parent)
    validate_budget(bundle)
    if bounds['aggregate_capture_max_bytes']>doc['budget']['capture_bytes']:raise ValueError('complete selected capture budget exceeded')
    return bundle

def plan_bytes(bundle):
    validate_plan(bundle.document['measurement_state'],bundle.cases)
    rows=[MAGIC.decode().rstrip('\n'),bundle.sha256,sha_plan(bundle),str(len(bundle.cases))]
    for row in bundle.document['measurement_state']['cases']:
        c=bundle.cases[row['case']]
        rows.append('\t'.join([c['id'],c['function'],c['partition']]+[str(row[r]) for r in ROLES]))
    body=('\n'.join(rows)+'\n').encode('ascii')
    return body+hashlib.sha256(body).hexdigest().encode()+b'\n'

def generated(bundle):
    blob=plan_bytes(bundle)
    header=('// Generated only from the frozen registry.\n#pragma once\n#include "state_executor.hpp"\n'
      'namespace ae_measurement_generated {\nstatic const unsigned char kBlob[] '
      '__attribute__((section(".ae_measurement"),used,aligned(1))) = {'+','.join(map(str,blob))+'};\n'
      'inline ae_state::Plan plan(){return ae_state::Plan::parse(kBlob,sizeof(kBlob));}\n}\n').encode()
    return {'measurement_state.bin':blob,'measurement_state.hpp':header,'state_executor.hpp':EXECUTOR.read_bytes()}

def embedded(path,bundle):
    from arch_explorer.components.accelsim.microcatalog import elf_sections
    sections,_=elf_sections(path);section=sections.get(SECTION)
    if (section is None or section['type']!=1 or not section['flags']&2 or section['flags']&1 or section['bytes']!=plan_bytes(bundle)):
        raise ValueError('actual ELF measurement plan differs from complete registry/lifecycle')
    return {'sha256':digest(section['bytes']),'bytes':len(section['bytes'])}
